/** lucide 그림 하나(react-native-svg). */
export function Glyph({
  name,
  size,
  color,
  strokeWidth = 2.25,
}: {
  name: GlyphName;
  size: number;
  color: string;
  strokeWidth?: number;
}) {
  const Icon = GLYPHS[name];
  return <Icon size={size} color={color} strokeWidth={strokeWidth} />;
}
