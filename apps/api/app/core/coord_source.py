"""좌표의 출처 — 확인자료와 동의 게이트가 함께 쓰는 어휘 (T-329).

`location_access_log`가 좌표를 적을 때, 그것이 **사용자 자신의 위치**인지 **사용자가 지도에서
고른 지점**인지 구분하지 않으면 기록도 게이트도 정확할 수 없다.

- 기록: 지도 클릭까지 "당신의 위치를 사용했다"고 적으면 위치정보법 제16조 확인자료가 부정확해진다.
- 게이트: 구분이 없으면 좌표 endpoint에 동의를 걸 수 없다. 걸면 지도에서 POI를 고르는 기능이
  깨지고, 안 걸면 철회한 사용자의 실제 위치도 통과한다(T-327이 `/regions/*`와
  `POST /features/requests`를 미게이트로 남긴 이유가 이것이다).

**한계 — 이 값은 클라이언트의 선언이다.** 서버는 좌표만 보고 그것이 단말 측위 결과인지 지도 탭
결과인지 알 수 없으므로 `map_pick`이라 거짓 선언하면 게이트를 지난다. 그럼에도 의미가 있는 이유:

- 게이트가 막으려는 것은 **자사 클라이언트가 철회를 존중하지 않는 것**이지 적대적 클라이언트가
  아니다. 적대적 클라이언트는 자기 자격증명으로 자기 좌표를 보내는 것이라 위협 모델이 다르다.
- 거짓 선언도 확인자료에 그대로 남는다 — 감사가 사후에 그것을 드러낼 수 있다.
- `device`를 요구하는 경로(`/features/nearby`, `/search` near-me)는 endpoint의 의미상 좌표가
  사용자 위치일 수밖에 없으므로 애초에 선언을 받지 않고 서버가 고정한다.

이 어휘를 스키마도 미들웨어도 아닌 `core`에 두는 이유는 양쪽이 함께 쓰기 때문이다 — 스키마가
미들웨어를 import하면 계층이 뒤집힌다.
"""

